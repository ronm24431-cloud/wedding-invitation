/*
   Friday
   20 November 2026
   9:00 PM
   Egypt time
*/

const weddingDate =
    new Date(
        "2026-11-20T21:00:00+02:00"
    ).getTime();


const countdownDays =
    document.getElementById(
        "countdownDays"
    );

const countdownHours =
    document.getElementById(
        "countdownHours"
    );

const countdownMinutes =
    document.getElementById(
        "countdownMinutes"
    );

const countdownSeconds =
    document.getElementById(
        "countdownSeconds"
    );


function updateCountdown() {

    const now =
        Date.now();


    const distance =
        weddingDate - now;


    if (distance <= 0) {

        countdownDays.textContent =
            "00";

        countdownHours.textContent =
            "00";

        countdownMinutes.textContent =
            "00";

        countdownSeconds.textContent =
            "00";

        return;

    }


    const days =
        Math.floor(
            distance /
            (1000 * 60 * 60 * 24)
        );


    const hours =
        Math.floor(
            (distance /
                (1000 * 60 * 60)) %
            24
        );


    const minutes =
        Math.floor(
            (distance /
                (1000 * 60)) %
            60
        );


    const seconds =
        Math.floor(
            (distance /
                1000) %
            60
        );


    countdownDays.textContent =
        String(days).padStart(
            2,
            "0"
        );


    countdownHours.textContent =
        String(hours).padStart(
            2,
            "0"
        );


    countdownMinutes.textContent =
        String(minutes).padStart(
            2,
            "0"
        );


    countdownSeconds.textContent =
        String(seconds).padStart(
            2,
            "0"
        );

}


/* =====================================
   START COUNTDOWN
===================================== */

updateCountdown();

setInterval(
    updateCountdown,
    1000
);
