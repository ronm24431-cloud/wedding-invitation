/* =====================================
   SET LANGUAGE
===================================== */

function setLanguage(language) {

    currentLanguage = language;

    const t = translations[language];


    document.documentElement.lang =
        language;

    document.documentElement.dir =
        language === "ar"
            ? "rtl"
            : "ltr";


    /*
        General translated elements
    */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            if (t[key]) {

                if (key === "invitationRequest") {

                    element.innerHTML =
                        t[key];

                } else {

                    element.textContent =
                        t[key];

                }

            }

        });


    /*
        Placeholders
    */

    document
        .querySelectorAll("[data-i18n-placeholder]")
        .forEach(element => {

            const key =
                element.dataset.i18nPlaceholder;

            if (t[key]) {

                element.placeholder =
                    t[key];

            }

        });


    /*
        Couple names
        Works even if the HTML
        only has IDs.
    */

    const groomName =
        document.getElementById("groomName");

    const brideName =
        document.getElementById("brideName");


    if (groomName) {

        groomName.textContent =
            t.groomName;

    }


    if (brideName) {

        brideName.textContent =
            t.brideName;

    }


    /*
        Language buttons
    */

    document
        .getElementById("arBtn")
        .classList
        .toggle(
            "active",
            language === "ar"
        );


    document
        .getElementById("enBtn")
        .classList
        .toggle(
            "active",
            language === "en"
        );


    updateGameText();

    updateMusicButton();


    localStorage.setItem(
        "weddingLanguage",
        language
    );

}


/* =====================================
   UPDATE GAME TEXT
===================================== */

function updateGameText() {

    const t =
        translations[currentLanguage];


    const titles = [

        t.findHeart,
        t.findRing,
        t.findDress,
        t.findSuit

    ];


    const instructions = [

        t.heartInstruction,
        t.ringInstruction,
        t.dressInstruction,
        t.suitInstruction

    ];


    gameTitle.textContent =
        titles[currentLevel - 1];

    gameInstruction.textContent =
        instructions[currentLevel - 1];

    updateProgress();

}


function updateProgress() {

    const dots = document.querySelectorAll(".progress-dot");

    dots.forEach((dot, index) => {
        dot.classList.toggle("active", index === currentLevel - 1);
        dot.classList.toggle("completed", index < currentLevel - 1);
    });
}


