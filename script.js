function showScreen(screen) {

    document
        .querySelectorAll(".screen")
        .forEach(item => {

            item.classList.remove("active");

        });


    setTimeout(() => {

        screen.classList.add("active");

        if (screen === invitationScreen) {
            invitationScreen.scrollTop = 0;
        }

    }, 50);

}


