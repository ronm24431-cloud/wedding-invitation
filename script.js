/* =====================================
   PREPARE GAME
===================================== */

function prepareGame() {

    const items =
        document.querySelectorAll(
            ".game-item"
        );


    const types = [

        "heart",
        "ring",
        "dress",
        "suit"

    ];


    items.forEach((item, index) => {

        const type =
            types[index];

        item.innerHTML =
            illustrations[type];

        item.dataset.item =
            type;

        item.classList.remove(
            "correct-item"
        );

        item.style.transform =
            "";

    });


    const correctType =
        types[currentLevel - 1];


    const correctItem =
        document.querySelector(
            `.game-item[data-item="${correctType}"]`
        );


    if (correctItem) {

        correctItem.classList.add(
            "correct-item"
        );

    }

}


/* =====================================
   GAME ITEM CLICK
===================================== */

document
    .querySelectorAll(".game-item")
    .forEach(item => {

        item.addEventListener(
            "click",
            () => {

                const correctType = [

                    "heart",
                    "ring",
                    "dress",
                    "suit"

                ][currentLevel - 1];


                if (
                    item.dataset.item ===
                    correctType
                ) {

                    handleCorrectAnswer();

                } else {

                    item.style.transform =
                        "scale(0.85)";


                    setTimeout(() => {

                        item.style.transform =
                            "";

                    }, 300);

                }

            }
        );

    });


/* =====================================
   CORRECT ANSWER
===================================== */

let answerLocked = false;

function handleCorrectAnswer() {

    if (answerLocked) return;
    answerLocked = true;

    if (currentLevel < 4) {

        showSuccess();


        setTimeout(() => {

            currentLevel++;
            answerLocked = false;

            updateGameText();

            showScreen(gameScreen);

            prepareGame();

        }, 2000);

    } else {

        showFinalSuccess();

    }

}


